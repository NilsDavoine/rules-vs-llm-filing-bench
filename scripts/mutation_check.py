"""Prove that the guard's tests can fail.

For each mutant: back guard.py up, break it on purpose, run the guard tests
(they MUST go red), restore guard.py from the backup copy (not from git),
check the restored file is byte-identical, run the tests again (green).
Writes results/mutation.md.

    python scripts/mutation_check.py
"""
import datetime as dt
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "filing_bench", "guard.py")

MUTANTS = [
    ("the guard accepts every date",
     "    if period == NO_DATE:\n        return True\n    m = PERIOD_RE",
     "    return True  # MUTANT\n    if period == NO_DATE:\n        return True\n    m = PERIOD_RE"),
    ("a blocked date keeps its year folder",
     '    if re.match(r"^\\d{4}/", proposal.folder or ""):\n        proposal.folder = TO_SORT\n',
     ""),
    ("a month is accepted when only its year is shown",
     "    return (year, int(m.group(2))) in marks",
     "    return any(y == year for y, _ in marks)"),
]


def digest(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def run_tests():
    env = dict(os.environ, PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    r = subprocess.run([sys.executable, "-m", "pytest", "-o", "addopts=", "-q", "-p", "no:cacheprovider", "tests/test_guard.py"],
                       cwd=ROOT, env=env, capture_output=True, text=True)
    lines = [l for l in r.stdout.splitlines() if " passed" in l or " failed" in l]
    last = lines[-1].strip() if lines else r.stdout.strip().splitlines()[-1]
    return r.returncode, last


def main():
    original = digest(TARGET)
    backup_dir = tempfile.mkdtemp(prefix="guard-backup-")
    backup = os.path.join(backup_dir, "guard.py")
    shutil.copy2(TARGET, backup)
    rows, ok = [], True
    code, last = run_tests()
    rows.append(("(none, before)", "green" if code == 0 else "RED", last))
    ok &= code == 0
    for label, old, new in MUTANTS:
        with open(TARGET, encoding="utf-8") as f:
            src = f.read()
        assert old in src, f"mutant '{label}' no longer applies: update the script"
        try:
            with open(TARGET, "w", encoding="utf-8") as f:
                f.write(src.replace(old, new, 1))
            code, last = run_tests()
            rows.append((label, "RED (caught)" if code else "green (MISSED)", last))
            ok &= code != 0
        finally:
            shutil.copy2(backup, TARGET)
            assert digest(TARGET) == original, "restore from backup failed"
    code, last = run_tests()
    rows.append(("(none, after restore)", "green" if code == 0 else "RED", last))
    ok &= code == 0
    shutil.rmtree(backup_dir)

    out = ["# Mutation check of the date guard", "",
           f"Generated by `python scripts/mutation_check.py` on {dt.date.today().isoformat()}.", "",
           "Each mutant breaks `filing_bench/guard.py` on purpose; `tests/test_guard.py` must turn red. "
           "The file is then restored from a backup copy and checked byte for byte (sha256 "
           f"`{original[:12]}`).", "",
           "| mutant | tests | pytest summary |", "|---|---|---|"]
    out += [f"| {a} | {b} | `{c}` |" for a, b, c in rows]
    out += ["", "Result: " + ("every mutant was caught." if ok else "**a mutant survived.**"), ""]
    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    with open(os.path.join(ROOT, "results", "mutation.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("\n".join(out))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
